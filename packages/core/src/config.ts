import { config } from 'dotenv';
import { resolve, join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { existsSync, mkdirSync, writeFileSync } from 'fs';
import { randomBytes } from 'crypto';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Resolve .env path respecting MCP_ENV_FILE or cwd
export function resolveEnvPath(): string {
  return process.env.MCP_ENV_FILE || resolve(process.cwd(), '.env');
}

export function loadEnv(envPath?: string): void {
  config({ path: envPath || resolve(process.cwd(), '.env'), override: true });
}

export interface ConfigCheckResult {
  valid: boolean;
  missing: string[];
  dbProvider: string;
}

export function checkConfig(): { valid: boolean; missing: string[]; dbProvider: string } {
  const missing: string[] = [];
  const dbProvider = process.env.MCP_DB_PROVIDER || process.env.DB_PROVIDER || '';
  
  if (!dbProvider) missing.push('MCP_DB_PROVIDER (sqlite or d1)');
  
  const encKey = process.env.MCP_ENCRYPTION_KEY;
  if (!encKey || encKey === 'default-secret-key') {
    missing.push('MCP_ENCRYPTION_KEY (generate with: openssl rand -hex 32)');
  }
  
  if (dbProvider === 'd1') {
    if (!process.env.CLOUDFLARE_ACCOUNT_ID) missing.push('CLOUDFLARE_ACCOUNT_ID');
    if (!process.env.CLOUDFLARE_DATABASE_ID) missing.push('CLOUDFLARE_DATABASE_ID');
    if (!process.env.CLOUDFLARE_API_TOKEN) missing.push('CLOUDFLARE_API_TOKEN (with D1:Edit permission)');
  }
  
  if (dbProvider === 'sqlite') {
    if (!process.env.MCP_STORAGE_FILE) missing.push('MCP_STORAGE_FILE (path to SQLite database file)');
  }
  
  return { valid: missing.length === 0, missing, dbProvider };
}

export async function verifyDBConnection(dbProvider: string): Promise<{ success: boolean; error?: string }> {
  try {
    if (dbProvider === 'd1') {
      // Dynamic import to avoid circular dependency with storage-d1
      const storageD1 = await import('@mcp-ecc/storage-d1') as { CloudflareD1Database: new (accountId: string, databaseId: string, apiToken: string) => { prepare: (sql: string) => { first: () => Promise<unknown> } } };
      const db = new storageD1.CloudflareD1Database(
        process.env.CLOUDFLARE_ACCOUNT_ID!,
        process.env.CLOUDFLARE_DATABASE_ID!,
        process.env.CLOUDFLARE_API_TOKEN!
      );
      
      await db.prepare('SELECT 1').first();
      return { success: true };
    } else if (dbProvider === 'sqlite') {
      const storageFile = process.env.MCP_STORAGE_FILE;
      if (!storageFile) return { success: false, error: 'MCP_STORAGE_FILE not set' };
      
      const dir = dirname(storageFile);
      if (!existsSync(dir)) {
        mkdirSync(dir, { recursive: true });
      }
      
      // Test write access
      const testFile = join(dirname(storageFile), '.write-test');
      writeFileSync(testFile, 'test');
      const fs = await import('fs');
      fs.unlinkSync(testFile);
      
      return { success: true };
    }
    return { success: false, error: `Unknown database provider: ${dbProvider}` };
  } catch (error) {
    return { success: false, error: error instanceof Error ? error.message : String(error) };
  }
}

export function generateEncryptionKey(): string {
  return randomBytes(32).toString('hex');
}

export interface EnvConfig {
  encryptionKey: string;
  dbProvider: string;
  dbConfig: Record<string, string>;
  serverConfig: {
    port: string;
    host: string;
    publicUrl: string;
    sessionSecret: string;
  };
}

export function buildEnvContent(config: EnvConfig): string {
  const envLines = [
    '# mcp-ecc environment configuration',
    '# Generated by mcp-ecc setup',
    '',
    '# === Required ===',
    '# Master key used to encrypt stored credentials (AES-256-GCM).',
    '# Generate with:  openssl rand -hex 32',
    `MCP_ENCRYPTION_KEY=${config.encryptionKey}`,
    '',
    '# === Database Provider ===',
    `MCP_DB_PROVIDER=${config.dbProvider}`,
  ];
  
  if (config.dbProvider === 'd1') {
    envLines.push(
      '',
      '# --- Cloudflare D1 Configuration ---',
      `CLOUDFLARE_ACCOUNT_ID=${config.dbConfig.CLOUDFLARE_ACCOUNT_ID}`,
      `CLOUDFLARE_DATABASE_ID=${config.dbConfig.CLOUDFLARE_DATABASE_ID}`,
      `CLOUDFLARE_API_TOKEN=${config.dbConfig.CLOUDFLARE_API_TOKEN}`,
    );
  } else {
    envLines.push(
      '',
      '# --- SQLite Configuration ---',
      `MCP_STORAGE_FILE=${config.dbConfig.MCP_STORAGE_FILE}`,
    );
  }
  
  envLines.push(
    '',
    '# === Server / networking ===',
    `HOST_PORT=${config.serverConfig.port}`,
    `HOST=${config.serverConfig.host}`,
    `PUBLIC_URL=${config.serverConfig.publicUrl}`,
    `SESSION_SECRET=${config.serverConfig.sessionSecret || ''}`,
    '',
    '# === Optional: override the Docker image used by docker-compose ===',
    '# MCP_ECC_IMAGE=ghcr.io/karljsamuel/mcp-ecc:beta',
  );
  
  return envLines.join('\n') + '\n';
}

export function writeEnvFile(envPath: string, content: string): void {
  writeFileSync(envPath, content);
}
